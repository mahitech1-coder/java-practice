package com.loops;

public class Demo1 {

	public static void main(String[] args) {
		for(int i=1;i<=10;i++) {
			System.out.print(i +" ");
		}
		for (int i = 20; i >= 1; i--) {
			System.out.print(i + " ");
		}
		for (int i = 2; i <= 50; i = i + 2) {
			System.out.print(i + " ");
		}
		for (int i = 1; i <= 50; i = i + 2) {
			System.out.print(i + " ");
		}
		
	}

}

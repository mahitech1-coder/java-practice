package com.loops;

//Print numbers from 1 to 10.
public class Testdemo22 {

	public static void main(String[] args) {
		for (int i = 1; i <= 10; i++) {
			System.out.print(i + " ");
		}
		System.out.println();
//		Print numbers from 10 to 1.
		for (int i = 10; i >= 1; i--) {
			System.out.print(i + " ");
		}

	}

}
